package attribution

import (
	"testing"

	"github.com/ku5ic/claude-kit/go/internal/testutil"
)

func TestFind(t *testing.T) {
	d := New(testutil.KitConfig(t).Attribution)
	for text, want := range map[string]bool{
		// Attribution, by any tool.
		"Co-Authored-By: Claude Opus <noreply@anthropic.com>":                    true,
		"Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>":   true,
		"Co-authored-by: devin-ai-integration[bot] <x@users.noreply.github.com>": true,
		"Assisted-by: Codex": true,
		"Claude-Session: https://claude.ai/code/session_x":                        true,
		"AI-Session-Id: 1234":                                                     true,
		"\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)": true,
		"Generated with ChatGPT":                                                  true,
		"Written by an AI":                                                        true,
		"Fixes it.\n\nhttps://claude.ai/code/session_013Ls":                       true,
		"see https://chatgpt.com/share/abc":                                       true,
		// Text about the tools, not attribution.
		"the Claude session reads its transcript once":                         false,
		"Co-authored-by: Jane Doe <jane@users.noreply.github.com>":             false,
		"SessionStart: reads the merged settings":                              false,
		"docs: claude-kit's README names the generated with claude-kit bundle": false,
		"Generated by go generate":                                             false,
		"Co-authored-by: Devin Smith <devin@corp.com>":                         false,
		"Reviewed-by: Cody Lee <cody@corp.com>":                                false,
		"Signed-off-by: Jane Doe <jane@openai.com>":                            false,
		"chore: bump express-session: 1.17 to 1.18":                            false,
		"fix cookie-session: expire on logout":                                 false,
		"Claude-Code-Session: abc":                                             true,
		"Cursor-Session-Id: abc":                                               true,
	} {
		if _, got := d.Find(text); got != want {
			t.Errorf("Find(%q) = %v, want %v", text, got, want)
		}
	}
}
