package bashguard

import (
	"path/filepath"
	"testing"

	"github.com/ku5ic/claude-kit/go/internal/testutil"
)

// Each case runs guard-attribution from a cwd holding signed.txt, a message
// with a co-author trailer, and clean.txt, against the real kit.yml.
func TestGuardAttribution(t *testing.T) {
	t.Parallel()
	k := newSandbox(t)
	cwd := testutil.Physical(t, t.TempDir())
	testutil.Write(t, filepath.Join(cwd, "signed.txt"), "fix: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n")
	testutil.Write(t, filepath.Join(cwd, "clean.txt"), "fix: x\n\nThe parser dropped the last line.\n")
	testutil.Write(t, filepath.Join(cwd, "signed.json"), `{"body": "x\n\nhttps://claude.ai/code/session_x"}`)
	for _, c := range []struct {
		name, cmd string
		status    int
	}{
		{"passthrough: not git or gh", `echo "Co-Authored-By: Claude"`, 0},
		{"passthrough: a git read names a trailer", `git log --grep "Claude-Session:"`, 0},
		{"passthrough: git add beside a heredoc naming one", "cat > docs/rules.md <<EOF\nNever add Co-Authored-By: Claude\nEOF\ngit add docs/rules.md", 0},
		{"passthrough: gh pr view", `gh pr view 3 --json body`, 0},
		// git: commit, merge, tag, notes, revert, and the rest that write a message
		{"block: Co-Authored-By Claude", `git commit -m "feat: x" -m "Co-Authored-By: Claude <claude@anthropic.com>"`, 2},
		{"block: Generated by Claude", `git commit -m "Generated by Claude"`, 2},
		{"block: a Claude-Session trailer", `git commit -m "feat: x" -m "Claude-Session: https://claude.ai/code/session_013Ls16w"`, 2},
		{"block: a bare Claude Code session link", `git commit -m "feat: x" -m "See https://claude.ai/code/session_013Ls16w"`, 2},
		{"block: another tool's co-author", `git commit -m "feat: x" -m "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>"`, 2},
		{"block: a --trailer", `git commit -m "feat: x" --trailer "Assisted-by: Codex"`, 2},
		{"block: a tag message", `git tag -a v1 -m "Generated with Claude Code"`, 2},
		{"block: a note", `git notes add -m "Co-Authored-By: Claude" HEAD`, 2},
		{"block: a merge message", `git merge --no-ff topic -m "Merge topic" -m "Co-Authored-By: Claude"`, 2},
		{"block: git -C dir commit -F a signed file", `git -C ` + cwd + ` commit -F signed.txt`, 2},
		{"block: commit -F a signed file", `git commit -F signed.txt`, 2},
		{"block: tag --file a signed file", `git tag -a v1 --file=signed.txt`, 2},
		{"block: a signature in a heredoc writing the -F file", "cat > /tmp/msg <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude <c@a.com>\nEOF\ngit commit -F /tmp/msg", 2},
		{"block: a signature in an unterminated commit heredoc", "git commit -m \"$(cat <<EOF\nfeat: x\nGenerated with Claude\n)\"", 2},
		{"block: a signature in a -m variable set earlier", "MSG=\"Generated with Claude\"\ngit commit -m \"$MSG\"", 2},
		{"block: a commit ended by a separator is still a commit", "git commit;echo \"Co-Authored-By: Claude\"", 2},
		{"block: a commit with its output redirected is still a commit", "git commit>out.log -m \"x\n\nCo-Authored-By: Claude\"", 2},
		{"block: a signature in a heredoc writing a file, even an unrelated one", "cat > notes.md <<EOF\nGenerated with Claude\nEOF\ngit commit -m \"feat: ok\"", 2},
		{"block: a signature in a heredoc opened on a continuation line", "git commit \\\n  -F - <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude <c@a.com>\nEOF", 2},
		{"block: a signature after a here-string", "v=$(tr a-z A-Z <<< hello)\ngit commit -m \"feat: x\n\nCo-Authored-By: Claude <c@a.com>\"", 2},
		{"block: a signature after an arithmetic shift", "n=$((1<<b))\ngit commit -m \"feat: x\n\nCo-Authored-By: Claude <c@a.com>\"", 2},
		{"allow: a message naming the Claude session", `git commit -m "fix(hooks): the Claude session reads its transcript once"`, 0},
		{"allow: commit -F a clean file", `git commit -F clean.txt`, 0},
		{"allow: a human co-author", `git commit -m "feat: x" -m "Co-authored-by: Jane Doe <jane@users.noreply.github.com>"`, 0},
		// gh: pr, issue, release text, and api fields
		{"block: the Claude Code PR footer", "gh pr create -t \"fix: x\" -b \"Fixes it.\n\n\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)\"", 2},
		{"block: a session link in a PR body", `gh pr create -t "fix: x" -b "https://claude.ai/code/session_013Ls16w"`, 2},
		{"block: a PR body file with a trailer", `gh pr edit 3 --body-file signed.txt`, 2},
		{"block: an issue comment", `gh issue comment 3 -b "Generated with ChatGPT"`, 2},
		{"block: release notes", `gh release create v1 --notes "Generated with Claude Code"`, 2},
		{"block: release notes from a file", `gh release edit v1 -F signed.txt`, 2},
		{"block: a gh api field", `gh api repos/o/r/issues/3/comments -f body="Co-Authored-By: Claude"`, 2},
		{"block: a gh api --input body", `gh api repos/o/r/pulls -X POST --input signed.json`, 2},
		{"allow: a clean PR", `gh pr create -t "fix: x" -b "Reads the body from disk."`, 0},
		// glab: merge request, note, and api text
		{"block: an MR description file with a trailer", `glab mr create -t "fix: x" --description-file signed.txt`, 2},
		{"block: an MR note", `glab mr note 3 -m "Generated with Claude Code"`, 2},
		{"block: a glab api --input body", `glab api projects/1/merge_requests -X POST --input signed.json`, 2},
		{"allow: glab mr checkout", `glab mr checkout 3`, 0},
		{"allow: a clean MR", `glab mr create -t "fix: x" -d "Reads the body from disk."`, 0},
	} {
		t.Run(c.name, func(t *testing.T) {
			k.attribution(cwd, c.cmd).Want(t, c.status)
		})
	}
}

// A -F file under ~ or $HOME is read from a cwd elsewhere.
func TestGuardAttributionReadsTheFFileUnderHome(t *testing.T) {
	k := newSandbox(t)
	testutil.Write(t, filepath.Join(k.home, "signed.txt"), "fix: x\n\nCo-Authored-By: Claude <c@a.com>\n")
	k.attribution("", "git commit -F signed.txt && rm signed.txt").Want(t, 2)
	elsewhere := t.TempDir()
	k.attribution(elsewhere, "git commit -F ~/signed.txt").Want(t, 2)
	k.attribution(elsewhere, `git commit -F "$HOME/signed.txt"`).Want(t, 2)
}
